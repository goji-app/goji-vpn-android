 * - содержимое журнала приложения (AppLogger dlog/dloge) — это developer-логи для саппорта,
 *   а не пользовательский текст;
 * - названия/описания тарифов (PlanUi.name/description) — приходят с бэкенда (Remnawave),
 *   их язык не зависит от переключателя в приложении;
 * - "сырые" сообщения ошибок сети/сервера (it.message из HTTP-исключений) — используются как
